import numpy as np
import pandas as pd

data = {
    'social media plateform' : ['Twitter','facebook','Instagram','Aratai',
                                'Twitter','facebook','Instagram','Aratai'],
    'reviews' : ['It give hate speech','somehow ok','i love this one ','Indian Plateform',
                'It give hate speech','somehow ok','i love this one ','Indian Plateform'],
    'age': [21,23,34,45,np.nan,32,45,np.nan],
    'sentiment' : [1,0,1,1,0,0,1,1] #1 for postive and 0 for negative
}
#create a dataFrame
df = pd.DataFrame(data)
print(df)

def count_word(reviews):
  # count the number of word in each review
  # assuming this is 1D array
  return np.array([len(review.split()) for review in reviews ]).reshape(-1,1)

from sklearn.preprocessing import FunctionTransformer
# create the function transformer using count Word

word_count_transformer = FunctionTransformer(count_word)

from sklearn.pipeline import FeatureUnion
from sklearn.feature_extraction.text import CountVectorizer

feature_union = FeatureUnion([
    ('word_count', word_count_transformer),
    ('bag_of_words' , CountVectorizer())
])

from sklearn.compose import ColumnTransformer
from sklearn.impute import SimpleImputer
from sklearn.preprocessing import OneHotEncoder

column_transformer = ColumnTransformer(
    transformers=[
        ('age_imputer', SimpleImputer(strategy='mean'), ['age']),
        ('plateform_ohe', OneHotEncoder(), ['social media plateform']),
        ('review_processing', feature_union, 'reviews')
    ],
    remainder='drop'
)

from sklearn.pipeline import Pipeline
from sklearn.linear_model import LogisticRegression
from sklearn.preprocessing import MaxAbsScaler
from sklearn.feature_selection import SelectKBest , chi2

final_pipeline = Pipeline(steps=[
    ('col_transformer', column_transformer),
    ('scaler', MaxAbsScaler()),
    ('selector', SelectKBest(score_func=chi2, k=8)),
    ('classifier', LogisticRegression())
])

final_pipeline.fit(df.drop(columns=['sentiment']),df['sentiment'])

import numpy as np
import pandas as pd

# Set seed for reproducibility
np.random.seed(42)

# Generate 100 random values for IQ (typically between 80 and 140)
iq = np.random.randint(80, 140, size=100)

# Generate 100 random values for CGPA (typically between 5.0 and 10.0)
cgpa = np.round(np.random.uniform(5.0, 10.0, size=100), 2)

# Generate placement label (0 or 1) based on a simple relationship with IQ and CGPA to make it learnable
# Probabilistic model: higher IQ and CGPA increase the chance of placement
prob = 1 / (1 + np.exp(-(0.1 * (iq - 100) + 2.5 * (cgpa - 7.5))))
placement = np.random.binomial(1, prob)

# Create DataFrame
students_df = pd.DataFrame({
    'IQ': iq,
    'CGPA': cgpa,
    'Placement': placement
})

# Save to CSV
csv_path = 'students_placement.csv'
students_df.to_csv(csv_path, index=False)
print(f"Dataset successfully created and saved to '{csv_path}'!")

# Display the first few rows of the generated dataset
display(students_df.head())
print(f"Total samples: {len(students_df)}")
