import requests
from bs4 import BeautifulSoup
import pandas as pd

cache_url = 'https://webcache.googleusercontent.com/search?q=cache:https://www.ambitionbox.com/list-of-companies?campaign=desktop_nav%26page=10'
headers = {
    'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36'
}

try:
    response = requests.get(cache_url, headers=headers, timeout=15)
    if response.status_code == 200:
        soup = BeautifulSoup(response.text, 'html.parser')

        # Find all company name elements (usually <h2> with class containing 'companyName' or stripped text)
        companies = []
        ratings = []
        reviews = []

        # Search for company headers by targeting the typical AmbitionBox CSS classes
        for company_div in soup.find_all('div', class_='companyCardWrapper'):
            name_tag = company_div.find('h2', class_='companyCardWrapper__companyName')
            rating_tag = company_div.find('span', class_='companyCardWrapper__companyRatingValue')
            review_tag = company_div.find('span', class_='companyCardWrapper__ActionCount')

            if name_tag:
                companies.append(name_tag.text.strip())
                ratings.append(rating_tag.text.strip() if rating_tag else "N/A")
                reviews.append(review_tag.text.strip() if review_tag else "N/A")

        # Fallback: if class-based extraction returned empty, fetch general h2 elements
        if not companies:
            for h2 in soup.find_all('h2'):
                text = h2.text.strip()
                if text and len(text) > 1 and "AmbitionBox" not in text:
                    companies.append(text)
                    ratings.append("N/A")
                    reviews.append("N/A")

        # Create a DataFrame to display the scraped results
        df = pd.DataFrame({
            'Company Name': companies,
            'Rating': ratings,
            'Reviews': reviews
        })

        print(f"Successfully parsed {len(df)} companies!")
        print(df.head(10))
    else:
        print(f"Failed with status code: {response.status_code}")
except Exception as e:
    print(f"An error occurred: {e}")

